namespace Hizu.Application.Common.Interfaces;

/// <summary>
/// Result returned by Bale Safir OTP message delivery.
/// </summary>
/// <param name="Success">Whether the message was accepted and dispatched by Bale.</param>
/// <param name="MessageId">Unique message identifier returned by Bale.</param>
/// <param name="ErrorCode">Bale error code if request failed (e.g., 17 = NotBaleUser, 3 = RateLimitExceeded, etc.).</param>
/// <param name="ErrorMessage">Bale error description.</param>
/// <param name="IsNotBaleUser">True if recipient phone number has no active Bale account (Error 17).</param>
public record BaleOtpResult(
    bool Success,
    string? MessageId = null,
    int? ErrorCode = null,
    string? ErrorMessage = null,
    bool IsNotBaleUser = false
);

/// <summary>
/// Service for delivering OTP verification codes directly to Iranian phone numbers via Bale Safir API.
/// Official documentation: https://docs.bale.ai/safir
/// </summary>
public interface IBaleOtpService
{
    /// <summary>
    /// Sends an OTP verification message to the specified phone number using Bale's Safir API.
    /// </summary>
    /// <param name="phoneNumber">Iranian phone number (e.g. 09121234567 or 989121234567).</param>
    /// <param name="otp">The one-time passcode generated by the application.</param>
    /// <param name="requestId">Unique idempotency request ID. If null, a new GUID is generated.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>A BaleOtpResult containing dispatch status and details.</returns>
    Task<BaleOtpResult> SendOtpAsync(
        string phoneNumber,
        string otp,
        string? requestId = null,
        CancellationToken cancellationToken = default);
}
